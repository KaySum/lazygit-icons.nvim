-- Regenerates lua/lazygit-icons/icons.lua from lazygit's icon table. Run from anywhere:
--   nvim -l scripts/generate.lua [lazygit version, defaults to the installed one]

local version = arg[1] or vim.fn.system({ "lazygit", "--version" }):match(", version=([%d.]+)")
local url = ("https://raw.githubusercontent.com/jesseduffield/lazygit/v%s/pkg/gui/presentation/icons/file_icons.go"):format(
  version
)
local source = vim.fn.system({ "curl", "-fsSL", url })
assert(vim.v.shell_error == 0, "failed to fetch " .. url)

local function codepoint(hex)
  return vim.fn.nr2char(tonumber(hex, 16))
end

local maps = { nameIconMap = {}, extIconMap = {} }
local highlights = {}
local current
for line in vim.gsplit(source, "\n") do
  current = maps[line:match("^var (%w+) = map")] or current
  local key, glyph, color = line:match('^%s*"([^"]+)":%s*{Icon: "([^"]+)", Color: "#(%x+)"}')
  if key and current then
    local hl = "LazygitIcon" .. color:upper()
    glyph = glyph:gsub("\\U(%x%x%x%x%x%x%x%x)", codepoint):gsub("\\u(%x%x%x%x)", codepoint)
    current[key] = { glyph = glyph, hl = hl }
    highlights[hl] = "#" .. color:upper()
  end
end
assert(next(maps.nameIconMap) and next(maps.extIconMap), "no icons parsed from " .. url)

-- lazygit looks up the lowercased text after the last dot, so its mixed-case and multi-dot keys never match.
local extension = {}
for ext, icon in pairs(maps.extIconMap) do
  if ext == ext:lower() and not ext:find(".", 2, true) then
    extension[ext:sub(2)] = icon
  end
end

local out = { ("-- Generated by scripts/generate.lua from lazygit v%s. Do not edit."):format(version), "return {" }
local function section(name, tbl, format)
  table.insert(out, ("  %s = {"):format(name))
  local keys = vim.tbl_keys(tbl)
  table.sort(keys)
  for _, key in ipairs(keys) do
    table.insert(out, ("    [%q] = %s,"):format(key, format(tbl[key])))
  end
  table.insert(out, "  },")
end
local function icon(data)
  return ('{ glyph = "%s", hl = "%s" }'):format(data.glyph, data.hl)
end
section("highlights", highlights, function(color)
  return ("%q"):format(color)
end)
section("file", maps.nameIconMap, icon)
section("extension", extension, icon)
table.insert(out, "}")

local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.fn.writefile(out, root .. "/lua/lazygit-icons/icons.lua")
print(
  ("lazygit v%s: %d file names, %d extensions, %d colors\n"):format(
    version,
    vim.tbl_count(maps.nameIconMap),
    vim.tbl_count(extension),
    vim.tbl_count(highlights)
  )
)
